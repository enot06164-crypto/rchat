//! Разбор аргументов командной строки.
//!
//! Пароль никогда не передаётся аргументом: он либо запрашивается
//! интерактивно (без эха), либо читается из stdin (`--password-stdin`),
//! либо берётся из переменной окружения `RCHAT_PASSWORD` (для скриптов;
//! менее безопасно, потому что переменные окружения видны процессам
//! пользователя).

use std::path::PathBuf;

use clap::{Args, Parser, Subcommand};

#[derive(Parser, Debug)]
#[command(
    name = "rchat-cli",
    version,
    about = "CLI-клиент rchat: регистрация, чаты, сообщения и синхронизация",
    long_about = "Терминальный клиент rchat. Ядро клиента (rchat-core) не знает про \
                  конкретный транспорт, хранилище и CLI: этот бинарник собирает их вместе \
                  (WebSocket + TLS, SQLite, шифрованное файловое хранилище секретов)."
)]
pub struct Cli {
    /// URL сервера: ws://host:port (локально) или wss://host:port (TLS).
    #[arg(
        long,
        global = true,
        env = "RCHAT_SERVER",
        default_value = "ws://127.0.0.1:8443"
    )]
    pub server: String,

    /// Каталог локальных данных (БД, секреты). По умолчанию — системный
    /// каталог данных пользователя.
    #[arg(long, global = true, env = "RCHAT_DATA_DIR")]
    pub data_dir: Option<PathBuf>,

    /// Профиль (аккаунт) в каталоге данных. `default` — сам каталог данных,
    /// остальные профили лежат в `<каталог>/accounts/<имя>`; так несколько
    /// аккаунтов не смешивают БД, ключи и E2E-состояние.
    #[arg(long, global = true, env = "RCHAT_ACCOUNT", default_value = "default")]
    pub account: String,

    /// SHA-256 отпечаток TLS-сертификата сервера (hex, ':' допустимы) для
    /// пиннинга, например для самоподписанных сертификатов.
    #[arg(
        long,
        global = true,
        env = "RCHAT_TLS_FINGERPRINT",
        conflicts_with = "tls_insecure"
    )]
    pub tls_fingerprint: Option<String>,

    /// Отключить проверку TLS-сертификата (только явное локальное
    /// тестирование; в боевом режиме не использовать).
    #[arg(long, global = true, conflicts_with = "tls_fingerprint")]
    pub tls_insecure: bool,

    /// Имя этого устройства в списке устройств аккаунта.
    #[arg(long, global = true, env = "RCHAT_DEVICE_NAME")]
    pub device_name: Option<String>,

    /// Подробность логов: без флага — предупреждения, -v — info, -vv — debug.
    #[arg(short, long, global = true, action = clap::ArgAction::Count)]
    pub verbose: u8,

    #[command(subcommand)]
    pub command: Command,
}

/// Общие аргументы команд, требующих пароль.
#[derive(Args, Debug)]
pub struct PasswordArgs {
    /// Прочитать пароль одной строкой из stdin (для скриптов и тестов).
    #[arg(long)]
    pub password_stdin: bool,
}

#[derive(Subcommand, Debug)]
pub enum Command {
    /// Зарегистрировать нового пользователя и войти под ним.
    Register {
        /// Имя пользователя (логин).
        username: String,
        /// Отображаемое имя (по умолчанию совпадает с логином).
        #[arg(long)]
        display_name: Option<String>,
        #[command(flatten)]
        password: PasswordArgs,
    },

    /// Войти существующим пользователем.
    Login {
        username: String,
        #[command(flatten)]
        password: PasswordArgs,
    },

    /// Выйти: отозвать серверную сессию и удалить локальный токен.
    Logout {
        /// Дополнительно удалить локальные данные и E2E-состояние.
        #[arg(long)]
        wipe: bool,
    },

    /// Список локальных профилей (аккаунтов) в каталоге данных.
    Accounts,

    /// Удалить локальные данные профиля. Серверная сессия не отзывается:
    /// сначала выполните `--account <имя> logout`.
    AccountDelete {
        /// Имя профиля (не `default`: это сам каталог данных).
        name: String,
        /// Не спрашивать подтверждение (для скриптов).
        #[arg(long)]
        yes: bool,
    },

    /// Состояние соединения, сессии, курсора синхронизации и очереди.
    Status,

    /// Показать локальный профиль и текущую сессию.
    Me,

    /// Устройства аккаунта с отпечатками ключей. С `--chat` — устройства всех
    /// участников чата (для проверки отпечатка собеседника по независимому
    /// каналу).
    Devices {
        /// Чат: `chat_id` или логин собеседника.
        #[arg(long)]
        chat: Option<String>,
    },

    /// Отозвать устройство аккаунта по его идентификатору.
    RevokeDevice { device_id: String },

    /// Список чатов (локальный кеш, обновляется сервером).
    Chats,

    /// Создать личный чат с пользователем.
    ChatCreate {
        /// Логин собеседника.
        peer: String,
        /// Включить E2E (Olm v1): содержимое шифруется для устройств
        /// участников, сервер хранит только шифротекст.
        #[arg(long)]
        e2e: bool,
    },

    /// Создать групповой чат (создатель — владелец; участники получают
    /// немедленное членство). По умолчанию E2E: ключ Megolm рассылается
    /// устройствам участников.
    GroupCreate {
        /// Имя группы.
        name: String,
        /// Логины участников через запятую (например, `bob,carol`); можно
        /// пригласить позже командой `group invite`.
        #[arg(long, value_delimiter = ',', num_args = 0..)]
        members: Vec<String>,
        /// Создать без E2E (открытый текст; сервер должен разрешать dev-чаты).
        #[arg(long)]
        no_e2e: bool,
    },

    /// Операции с групповым чатом: состав, роли и владение.
    Group {
        #[command(subcommand)]
        command: GroupCommand,
    },

    /// Сигнализация звонков в личном чате: приглашение, принятие,
    /// отклонение и завершение. Медиа (WebRTC) не передаётся; события
    /// видны в `watch`.
    Call {
        #[command(subcommand)]
        command: CallCommand,
    },

    /// Отправить текстовое сообщение (чат задаётся id или логином собеседника).
    Send {
        /// Чат: `chat_id` или логин собеседника в личном чате.
        chat: String,
        /// Текст сообщения (слова соединяются пробелами).
        #[arg(required = true, num_args = 1..)]
        text: Vec<String>,
        /// Ответить на сообщение с данным server_id.
        #[arg(long)]
        reply_to: Option<u64>,
        /// Сколько секунд ждать подтверждения сервера; затем сообщение
        /// остаётся в очереди и уйдёт автоматически при подключении.
        #[arg(long, default_value_t = 10)]
        wait: u64,
    },

    /// История сообщений чата (локальная или с сервера).
    History {
        /// Чат: `chat_id` или логин собеседника.
        chat: String,
        #[arg(long, default_value_t = 50)]
        limit: u32,
        /// Загрузить с сервера (с расшифрованием), а не только из кеша.
        #[arg(long)]
        from_server: bool,
        /// Показать сообщения старше указанного server_id.
        #[arg(long)]
        before: Option<u64>,
    },

    /// Изменить текст собственного сообщения (только автор).
    Edit {
        /// Чат: `chat_id` или логин собеседника.
        chat: String,
        /// server_id сообщения (виден в `history`).
        server_id: u64,
        /// Новый текст (слова соединяются пробелами).
        #[arg(required = true, num_args = 1..)]
        text: Vec<String>,
    },

    /// Удалить собственное сообщение для всех участников (tombstone).
    Delete {
        /// Чат: `chat_id` или логин собеседника.
        chat: String,
        /// server_id сообщения (виден в `history`).
        server_id: u64,
    },

    /// Отметить сообщения чата прочитанными (read receipt).
    Read {
        /// Чат: `chat_id` или логин собеседника.
        chat: String,
        /// Прочитано до этого server_id; по умолчанию — до последнего в чате.
        #[arg(long)]
        up_to: Option<u64>,
    },

    /// Подтверждения доставки и прочтения по чату.
    Receipts {
        /// Чат: `chat_id` или логин собеседника.
        chat: String,
    },

    /// Однократно синхронизироваться с сервером.
    Sync,

    /// Слушать события (сообщения, presence, outbox) до Ctrl+C.
    Watch,
}

/// Операции с групповым чатом.
#[derive(Subcommand, Debug)]
pub enum GroupCommand {
    /// Состав и роли участников (из локального состояния; обновляется
    /// `sync`/`watch`).
    Info {
        /// Группа: `chat_id` или имя группы.
        chat: String,
    },

    /// Пригласить пользователей (может любой участник; членство наступает
    /// сразу, ключ E2E приглашённый получит со следующими сообщениями).
    Invite {
        /// Группа: `chat_id` или имя группы.
        chat: String,
        /// Логины через запятую.
        #[arg(required = true, value_delimiter = ',', num_args = 1..)]
        usernames: Vec<String>,
    },

    /// Покинуть группу. Владелец при выходе передаёт владение старейшему
    /// участнику; пустая группа не удаляется.
    Leave {
        /// Группа: `chat_id` или имя группы.
        chat: String,
    },

    /// Исключить участника (только владелец; владельца исключить нельзя).
    Remove {
        /// Группа: `chat_id` или имя группы.
        chat: String,
        /// Логин или user_id участника.
        user: String,
    },

    /// Переименовать группу (только владелец).
    Rename {
        /// Группа: `chat_id` или имя группы.
        chat: String,
        /// Новое имя.
        name: String,
    },
}

/// Сигнализация звонка (медиа нет).
#[derive(Subcommand, Debug)]
pub enum CallCommand {
    /// Пригласить собеседника на звонок (только личный чат; собеседник
    /// должен быть в сети).
    Invite {
        /// Чат: `chat_id` или логин собеседника.
        chat: String,
        /// Остаться в сети и ждать ответа (принятие/отклонение/завершение);
        /// без флага процесс завершается сразу и звонок снимается.
        #[arg(long)]
        wait: bool,
    },

    /// Принять входящий звонок по `call_id` (виден в `watch`).
    Accept {
        /// Идентификатор звонка.
        call_id: String,
    },

    /// Отклонить входящий звонок.
    Decline {
        /// Идентификатор звонка.
        call_id: String,
    },

    /// Завершить активный звонок (любой участник).
    End {
        /// Идентификатор звонка.
        call_id: String,
    },
}
